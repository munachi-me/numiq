/**
 * Regenerates the embedded sample CSV from `assets/sample-sales.csv`.
 *
 * The CSV is embedded rather than read at runtime so the helper works identically under
 * ESM, CommonJS, and browser bundlers without asset-loader configuration. A test asserts
 * the embedded text is byte-identical to the asset, so the two cannot drift.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

const csv = await readFile(path.join(root, "assets", "sample-sales.csv"), "utf8");
if (!csv.endsWith("\n")) throw new Error("assets/sample-sales.csv must end with a newline.");

const output = `// Generated by scripts/generate-sample.mjs from assets/sample-sales.csv. Do not edit.
//
// Embedded so useSampleDataset() behaves the same in Node, CommonJS, and browser builds.
export const SAMPLE_SALES_CSV = ${JSON.stringify(csv)};
`;

await writeFile(path.join(root, "src", "data", "sample-sales.ts"), output);
console.log("wrote src/data/sample-sales.ts");
